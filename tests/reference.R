bad <- 0
chk <- function(label, a, b, tol = 1e-6) {
    ok <- isTRUE(all.equal(as.numeric(a), as.numeric(b), tolerance = tol))
    cat(sprintf("%-46s %s\n", label, if (ok) "ok" else sprintf("DIFF  mine=%s ref=%s", paste(signif(as.numeric(a), 7)[1:min(3, length(a))], collapse = ","), paste(signif(as.numeric(b), 7)[1:min(3, length(b))], collapse = ","))))
    if (!ok) bad <<- bad + 1
}
data(columbus, package = "spdep")
d <- columbus; n <- nrow(d)
nb <- col.gal.nb
lw <- nb2listw(nb, style = "W")
Wsp <- as(as_dgRMatrix_listw(lw), "CsparseMatrix")
x <- d$CRIME
S <- sp_S(Wsp)
# ---- Moran, Geary, G
m <- sp_moran(x, Wsp, "randomisation", "greater")
r <- moran.test(x, lw, randomisation = TRUE)
chk("Moran I (randomisation)", m$stat, r$estimate[1]); chk("Moran var (rand)", m$var, r$estimate[3]); chk("Moran p (rand, greater)", m$p, r$p.value)
m <- sp_moran(x, Wsp, "normality", "two.sided"); r <- moran.test(x, lw, randomisation = FALSE, alternative = "two.sided")
chk("Moran var (normality)", m$var, r$estimate[3]); chk("Moran p (normality, 2-sided)", m$p, r$p.value)
g <- sp_geary(x, Wsp, "randomisation", "greater"); r <- geary.test(x, lw, randomisation = TRUE)
chk("Geary C", g$stat, r$estimate[1]); chk("Geary var (rand)", g$var, r$estimate[3]); chk("Geary p (rand, greater)", g$p, r$p.value)
g <- sp_geary(x, Wsp, "normality", "greater"); r <- geary.test(x, lw, randomisation = FALSE)
chk("Geary var (normality)", g$var, r$estimate[3]); chk("Geary p (normality)", g$p, r$p.value)
lwB <- nb2listw(nb, style = "B"); WB <- as(as_dgRMatrix_listw(lwB), "CsparseMatrix")
G <- sp_globalG(x, WB, "normality", "greater"); r <- globalG.test(x, lwB, alternative = "greater")
chk("General G", G$stat, r$estimate[1]); chk("General G var", G$var, r$estimate[3]); chk("General G p", G$p, r$p.value)
# ---- local statistics
li <- sp_local_moran(x, Wsp, nperm = 99)
ref <- localmoran(x, lw, alternative = "two.sided", conditional = FALSE)
chk("Local Moran Ii", li$Ii, ref[, 1]); chk("Local Moran E", li$E, ref[, 2])
chk("Local Moran Var (analytic)", li$V, ref[, 3]); chk("Local Moran Z", li$z, ref[, 4])
lg <- sp_local_g(x, WB, "W", star = TRUE, nperm = 99)
nbs <- include.self(nb); lws <- nb2listw(nbs, style = "W")
chk("Gi* z", lg$G, as.numeric(localG(x, lws)))
lg0 <- sp_local_g(x, WB, "W", star = FALSE, nperm = 99)
chk("Gi z", lg0$G, as.numeric(localG(x, lw)))
# ---- regression
f <- CRIME ~ INC + HOVAL
X <- model.matrix(f, d); y <- d$CRIME
tests <- sp_lm_tests(y, X, Wsp)
ref <- lm.RStests(lm(f, d), lw, test = "all")
chk("LM error", tests$stat[1], ref$RSerr$statistic); chk("LM lag", tests$stat[2], ref$RSlag$statistic)
chk("Robust LM error", tests$stat[3], ref$adjRSerr$statistic); chk("Robust LM lag", tests$stat[4], ref$adjRSlag$statistic)
chk("SARMA", tests$stat[5], ref$SARMA$statistic)
cmp <- function(label, fit, ref, hess = TRUE, tolb = 1e-4, tolse = 5e-3) {
    cf <- coef(ref)
    chk(paste(label, "ll"), fit$ll, as.numeric(logLik(ref)), 1e-6)
    chk(paste(label, "coef"), c(fit$rho, fit$lambda, fit$beta)[!is.na(c(fit$rho, fit$lambda, fit$beta))], cf[c(grep("^(rho|lambda)$", names(cf)), setdiff(seq_along(cf), grep("^(rho|lambda)$", names(cf))))], tolb)
}
fit <- sp_sreg(y, X, Wsp, "sar"); ref <- lagsarlm(f, d, lw)
cmp("SAR", fit, ref); chk("SAR rho", fit$rho, ref$rho, 1e-4)
refH <- lagsarlm(f, d, lw, control = list(fdHess = TRUE))
chk("SAR se (vs fdHess)", fit$coef$se, sqrt(diag(refH$fdHess)), 1e-3)
fit <- sp_sreg(y, X, Wsp, "sem"); ref <- errorsarlm(f, d, lw)
cmp("SEM", fit, ref); chk("SEM lambda", fit$lambda, ref$lambda, 1e-4)
fit <- sp_sreg(y, X, Wsp, "sdm", lagcols = 2:3); ref <- lagsarlm(f, d, lw, type = "mixed")
cmp("SDM", fit, ref); chk("SDM rho", fit$rho, ref$rho, 1e-4)
fit <- sp_sreg(y, X, Wsp, "sdem", lagcols = 2:3); ref <- errorsarlm(f, d, lw, etype = "emixed")
cmp("SDEM", fit, ref)
fit <- sp_sreg(y, X, Wsp, "slx", lagcols = 2:3); ref <- lmSLX(f, d, lw)
chk("SLX coef", fit$beta, coef(ref), 1e-8)
fit <- sp_sreg(y, X, Wsp, "sac"); ref <- sacsarlm(f, d, lw)
cmp("SAC", fit, ref); chk("SAC rho,lambda", c(fit$rho, fit$lambda), c(ref$rho, ref$lambda), 1e-3)
# ---- effects
fit <- sp_sreg(y, X, Wsp, "sar")
ef <- sp_effects_point(fit$rho, fit$beta, data.frame(b = 2:3, t = NA), Wsp, fit$ldeng)
im <- impacts(lagsarlm(f, d, lw), listw = lw)
chk("SAR direct", ef[, 1], im$direct, 1e-5); chk("SAR indirect", ef[, 2], im$indirect, 1e-5); chk("SAR total", ef[, 3], im$total, 1e-5)
fit <- sp_sreg(y, X, Wsp, "sdm", lagcols = 2:3)
ef <- sp_effects_point(fit$rho, fit$beta, data.frame(b = 2:3, t = 4:5), Wsp, fit$ldeng)
im <- impacts(lagsarlm(f, d, lw, type = "mixed"), listw = lw)
chk("SDM direct", ef[, 1], im$direct, 1e-5); chk("SDM indirect", ef[, 2], im$indirect, 1e-5)
# binary weights (not row-standardised)
fitB <- sp_sreg(y, X, WB, "sar", rowstd = FALSE); refB <- lagsarlm(f, d, lwB)
chk("SAR binary W rho", fitB$rho, refB$rho, 1e-4)
efB <- sp_effects_point(fitB$rho, fitB$beta, data.frame(b = 2:3, t = NA), WB, fitB$ldeng)
chk("SAR binary direct", efB[, 1], impacts(refB, listw = lwB)$direct, 1e-5)
# the total effect is the mean row sum of (I - rho W)^-1 times beta (checked by direct inversion; spatialreg reports another quantity for style B)
Sinv <- solve(diag(n) - fitB$rho * as.matrix(WB)); chk("SAR binary total (dense inverse)", efB[, 3], mean(rowSums(Sinv)) * fitB$beta[2:3], 1e-8)
cat(if (bad == 0) "\nAll reference checks passed.\n" else sprintf("\n%d reference check(s) failed.\n", bad))
if (bad > 0) quit(status = 1)
